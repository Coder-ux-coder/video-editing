"""Regenerate assets/samples/doctor_sample.{mp4,json}.

The sample is fully synthetic (FFmpeg's built-in flite voice + test pattern),
so it is free of any copyright and its ground truth is known exactly:
sentence texts, start/end times and the pauses between them. It contains a
deliberate retake (sentence 4 is said twice), an in-sentence stumble ("we are,
we are") and pauses of different lengths, so later phases can test silence
removal, stumble and retake detection against it, and `doctor` can check that
the speech model keeps disfluencies instead of silently tidying them away.

Needs an FFmpeg built with --enable-libflite (Ubuntu's ffmpeg has it). Users
never need to run this: the generated files are committed.

    python scripts/make_doctor_sample.py
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import wave
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "assets" / "samples"
SR = 16000
LEAD_IN = 0.8
TAIL = 1.0
NOISE_DBFS = -58.0  # quiet room tone, so silence detection is realistic

# (text spoken, pause after in seconds)
SCRIPT = [
    ("Hello, and welcome to the test clip.", 0.4),
    ("Today we are, we are going to bake a simple loaf of bread.", 1.2),  # in-sentence stumble
    ("First, mix four hundred grams of flour with warm water.", 0.6),
    ("Then let the dough rest for two hours.", 2.0),
    ("Then let the dough rest for two hours.", 0.5),   # retake of the previous line
    ("Finally, bake it at two hundred and twenty degrees for forty minutes.", 0.8),
    ("Thanks for watching, and see you next time.", 0.0),
]


def synth(text: str, path: Path) -> np.ndarray:
    safe = text.replace("'", "").replace(":", " ")
    subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi",
                    "-i", f"flite=text='{safe}':voice=slt", "-ar", str(SR), "-ac", "1",
                    "-c:a", "pcm_s16le", str(path)], check=True)
    with wave.open(str(path), "rb") as w:
        data = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float32) / 32768
    # Trim flite's own leading/trailing silence so our timings are exact.
    idx = np.nonzero(np.abs(data) > 0.01)[0]
    return data[idx[0]: idx[-1] + 1] if len(idx) else data


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(1234)
    pieces = [np.zeros(int(LEAD_IN * SR), np.float32)]
    t = LEAD_IN
    sentences = []
    with tempfile.TemporaryDirectory() as td:
        for i, (text, pause) in enumerate(SCRIPT):
            speech = synth(text, Path(td) / f"s{i}.wav")
            dur = len(speech) / SR
            sentences.append({"index": i, "text": text, "start": round(t, 3), "end": round(t + dur, 3),
                              "pause_after": pause, "retake_of": i - 1 if i > 0 and text == SCRIPT[i - 1][0] else None})
            pieces += [speech, np.zeros(int(pause * SR), np.float32)]
            t += dur + pause
        pieces.append(np.zeros(int(TAIL * SR), np.float32))
        audio = np.concatenate(pieces)
        audio += rng.normal(0, 10 ** (NOISE_DBFS / 20), len(audio)).astype(np.float32)
        audio = np.clip(audio * 0.7, -1, 1)
        wav = Path(td) / "speech.wav"
        with wave.open(str(wav), "wb") as w:
            w.setnchannels(1)
            w.setsampwidth(2)
            w.setframerate(SR)
            w.writeframes((audio * 32767).astype(np.int16).tobytes())
        duration = len(audio) / SR
        mp4 = OUT_DIR / "doctor_sample.mp4"
        subprocess.run(["ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
                        "-f", "lavfi", "-i", f"testsrc2=size=640x360:rate=25:duration={duration:.3f}",
                        "-i", str(wav), "-map", "0:v", "-map", "1:a",
                        "-c:v", "libx264", "-preset", "slow", "-crf", "34", "-pix_fmt", "yuv420p",
                        "-c:a", "aac", "-b:a", "64k", "-ar", "48000", "-ac", "1",
                        "-shortest", "-movflags", "+faststart", "-map_metadata", "-1", str(mp4)], check=True)
    meta = {
        "description": "Synthetic talking clip for `cutroom doctor` and tests. Generated by "
                       "scripts/make_doctor_sample.py with FFmpeg flite (voice 'slt') and testsrc2.",
        "licence": "Generated by Cutroom; no third-party content. Public domain (CC0).",
        "duration": round(duration, 3),
        "reference_text": " ".join(s for s, _ in SCRIPT),
        "stumble": {"sentence": 1, "phrase": "we are we are"},
        "sentences": sentences,
    }
    (OUT_DIR / "doctor_sample.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {mp4} ({mp4.stat().st_size / 1024:.0f} KB, {duration:.2f}s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
