"""Generate docs/TOOLS.md from the CLI itself, so the docs can never drift.

Typer 0.28 bundles its own copy of click (``typer._click``), so this walks the command
tree by duck typing (``.commands`` on groups, ``param_type_name`` on parameters) rather
than by isinstance checks against the external ``click`` package.
"""

from __future__ import annotations

import typer.main


def walk_commands(cmd, prefix: str = "cutroom") -> list[tuple[str, object]]:
    """All leaf commands as (full name, command), depth-first, sorted by name."""
    subs = getattr(cmd, "commands", None)
    if subs:
        out = []
        for name in sorted(subs):
            out += walk_commands(subs[name], f"{prefix} {name}")
        return out
    return [(prefix, cmd)]


def _param_line(p) -> str:
    help_ = (getattr(p, "help", None) or "").strip()
    if p.param_type_name == "argument":
        name = (p.name or "").upper()
        multi = "..." if p.nargs == -1 else ""
        req = "" if p.required else " (optional)"
        return f"- `{name}{multi}`{req}" + (f": {help_}" if help_ else "")
    opts = ", ".join(f"`{o}`" for o in [*p.opts, *getattr(p, "secondary_opts", [])])
    default = p.default
    is_flag = getattr(p, "is_flag", False)
    if not is_flag and default not in (None, (), []) and not callable(default):
        help_ += f" (default: {default})"
    return f"- {opts}" + (f": {help_}" if help_ else "")


def render_tools_md() -> str:
    from cutroom.cli import app

    root = typer.main.get_command(app)
    lines = [
        "# Cutroom tools",
        "",
        "<!-- Generated by `cutroom docs` from the CLI's own help text. Do not edit by hand. -->",
        "",
        "Every command accepts `--help`. Commands with `--json` print one JSON object on stdout;",
        "errors print a suggested fix and exit non-zero. Commands that act on a job append to",
        "`jobs/<id>/log.md` and `jobs/<id>/logs/commands.jsonl`.",
        "",
    ]
    for name, cmd in walk_commands(root):
        lines += [f"## `{name}`", ""]
        help_text = (getattr(cmd, "help", None) or "").strip()
        if help_text:
            lines += [help_text, ""]
        params = [p for p in cmd.params if p.name != "help"]
        if params:
            lines += ["Parameters:", ""] + [_param_line(p) for p in params] + [""]
    return "\n".join(lines).rstrip() + "\n"
