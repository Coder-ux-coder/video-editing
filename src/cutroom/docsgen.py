"""Generate docs/TOOLS.md from the CLI itself, so the docs can never drift.

Typer 0.28 bundles its own copy of click (``typer._click``), so this walks the command
tree by duck typing (``.commands`` on groups, ``param_type_name`` on parameters) rather
than by isinstance checks against the external ``click`` package.
"""

from __future__ import annotations

import typer.main


def walk_commands(cmd, prefix: str = "cutroom") -> list[tuple[str, object]]:
    """All leaf commands as (full name, command), depth-first, sorted by name."""
    subs = getattr(cmd, "commands", None)
    if subs:
        out = []
        for name in sorted(subs):
            out += walk_commands(subs[name], f"{prefix} {name}")
        return out
    return [(prefix, cmd)]


def _param_line(p) -> str:
    help_ = (getattr(p, "help", None) or "").strip()
    if p.param_type_name == "argument":
        name = (p.name or "").upper()
        multi = "..." if p.nargs == -1 else ""
        req = "" if p.required else " (optional)"
        return f"- `{name}{multi}`{req}" + (f": {help_}" if help_ else "")
    opts = ", ".join(f"`{o}`" for o in [*p.opts, *getattr(p, "secondary_opts", [])])
    default = p.default
    is_flag = getattr(p, "is_flag", False)
    if not is_flag and default not in (None, (), []) and not callable(default):
        help_ += f" (default: {default})"
    return f"- {opts}" + (f": {help_}" if help_ else "")


def render_tools_md() -> str:
    from cutroom.cli import app

    root = typer.main.get_command(app)
    lines = [
        "# Cutroom tools",
        "",
        "<!-- Generated by `cutroom docs` from the CLI's own help text. Do not edit by hand. -->",
        "",
        "Every command accepts `--help`. Commands with `--json` print one JSON object on stdout;",
        "errors print a suggested fix and exit non-zero. Commands that act on a job append to",
        "`jobs/<id>/log.md` and `jobs/<id>/logs/commands.jsonl`.",
        "",
    ]
    from cutroom.tools.registry import manifests

    lines += ["## Tool plugins", "", "Commands provided by modules in `src/cutroom/tools/` (see `registry.py`).", "",
              "| command | group | what it does | writes a new timeline version | tests |", "|---|---|---|---|---|"]
    for m in manifests():
        lines.append(f"| `{m.name}` | {m.group} | {m.summary} | {'yes' if m.changes_timeline else 'no'} | "
                     f"{', '.join(f'`{t}`' for t in m.tests)} |")
    lines.append("")
    for name, cmd in walk_commands(root):
        lines += [f"## `{name}`", ""]
        help_text = (getattr(cmd, "help", None) or "").strip()
        if help_text:
            lines += [help_text, ""]
        params = [p for p in cmd.params if p.name != "help"]
        if params:
            lines += ["Parameters:", ""] + [_param_line(p) for p in params] + [""]
    return "\n".join(lines).rstrip() + "\n"


def _type_name(annotation) -> str:
    import typing

    s = str(annotation)
    s = s.replace("typing.", "").replace("cutroom.timeline.model.", "").replace("<class '", "").replace("'>", "")
    return s.replace("NoneType", "None")


def render_timeline_schema_md() -> str:
    """docs/TIMELINE_SCHEMA.md: every model and field of the project file, from the code."""
    from cutroom.timeline import model as M

    models = [M.Timeline, M.Meta, M.ChangeEntry, M.SourceRef, M.Track, M.Clip, M.Keyframe, M.Transition, M.Effect,
              M.CutDecision, M.Graphic, M.Captions, M.CaptionCue, M.AudioSpec, M.Marker, M.Output]
    lines = ["# Timeline schema (`cutroom.timeline/1`)", "",
             "<!-- Generated by `cutroom docs` from src/cutroom/timeline/model.py. Do not edit by hand. -->", "",
             "One JSON file per version: `jobs/<id>/versions/vNNN.json` (immutable; `HEAD` names the current",
             "one). Times are seconds: `src_in`/`src_out` in source time, `start` in timeline time. The",
             "machine-readable JSON Schema is `docs/timeline.schema.json`. Validate with `cutroom validate`;",
             "never hand-edit version files, use cutroom commands (each writes a new version).", ""]
    for m in models:
        doc = (m.__doc__ or "").strip().splitlines()[0] if m.__doc__ and m is not M.Timeline else ""
        lines += [f"## {m.__name__}", ""] + ([doc, ""] if doc else [])
        lines += ["| field | type | default | description |", "|---|---|---|---|"]
        for name, f in m.model_fields.items():
            key = f.alias or name
            if f.is_required():
                default = "required"
            elif f.default_factory is not None:
                default = "`[]`" if f.default_factory is list else ("`{}`" if f.default_factory is dict else "auto")
            else:
                default = f"`{f.default!r}`"
            desc = (f.description or "").replace("|", "\\|")
            tname = _type_name(f.annotation).replace("|", "\\|")
            lines.append(f"| `{key}` | `{tname}` | {default} | {desc} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_timeline_json_schema() -> str:
    import json

    from cutroom.timeline.model import Timeline

    return json.dumps(Timeline.model_json_schema(by_alias=True), indent=1) + "\n"
